# Publishes a new version of English Coach to the "updates" branch on GitHub.
# The app checks that branch: a newer versionCode -> "Update" button; a newer content version -> lessons update silently.
#
# Usage (from the project folder):
#   powershell -ExecutionPolicy Bypass -File tools\publish.ps1 -Notes "What is new"
#
# Before publishing a new APK: raise versionCode/versionName in app/build.gradle.kts.
# For new lessons/words only: raise "version" in app/src/main/assets/course/manifest.json.
# The branch always holds a single commit (force push), so the repository does not grow with every APK.

param([string]$Notes = "")

$ErrorActionPreference = "Stop"
$root = Split-Path $PSScriptRoot -Parent
$repo = "https://github.com/dstpnklen20-hue/English-Coach.git"
$signing = "F:/AndroidDev/keys/english-coach-signing.properties"
$utf8 = New-Object System.Text.UTF8Encoding $false

if (-not (Test-Path $signing)) { throw "Signing key not found ($signing): an APK signed with another key will not install over the app." }

Push-Location $root
try {
    & .\gradlew.bat assembleRelease testDebugUnitTest -q
    if ($LASTEXITCODE -ne 0) { throw "Build or tests failed - nothing published." }

    $gradle = [IO.File]::ReadAllText("$root\app\build.gradle.kts", $utf8)
    $code = [int][regex]::Match($gradle, 'versionCode = (\d+)').Groups[1].Value
    $name = [regex]::Match($gradle, 'versionName = "([^"]+)"').Groups[1].Value
    $course = "$root\app\src\main\assets\course"
    $manifest = [IO.File]::ReadAllText("$course\manifest.json", $utf8) | ConvertFrom-Json

    $stage = Join-Path $env:TEMP "english-coach-updates"
    if (Test-Path $stage) { Remove-Item $stage -Recurse -Force }
    New-Item -ItemType Directory "$stage\content" | Out-Null

    Copy-Item "$root\app\build\outputs\apk\release\app-release.apk" "$stage\EnglishCoach.apk"
    $sha = (Get-FileHash "$stage\EnglishCoach.apk" -Algorithm SHA256).Hash.ToLower()

    $files = @("manifest.json") + $manifest.words
    foreach ($level in $manifest.levels) { foreach ($part in "grammar", "reading", "dialogs", "drills") { $files += "${level}_$part.json" } }
    foreach ($f in $files) { Copy-Item "$course\$f" "$stage\content\$f" }

    $info = [ordered]@{ versionCode = $code; versionName = $name; apk = "EnglishCoach.apk"; sha256 = $sha; notes = $Notes }
    [IO.File]::WriteAllText("$stage\update.json", ($info | ConvertTo-Json), $utf8)
    [IO.File]::WriteAllText("$stage\README.md", "Update channel of English Coach (generated by tools/publish.ps1, do not edit by hand).`n", $utf8)

    $email = git config user.email
    $user = git config user.name
    git -C $stage init -q -b updates
    git -C $stage add -A
    git -C $stage -c user.email=$email -c user.name=$user commit -q -m "English Coach $name (code $code), content v$($manifest.version)"
    # A big postBuffer: without it pushing the APK over HTTPS breaks with "unable to rewind rpc post data"
    git -C $stage -c http.postBuffer=157286400 push --force $repo updates
    if ($LASTEXITCODE -ne 0) { throw "Push failed." }

    Write-Host "Published: app $name (code $code), content v$($manifest.version), sha256 $sha"
}
finally {
    Pop-Location
}
